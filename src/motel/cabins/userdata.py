"""Cloud-init rendering and key generation. Every value is validated, so nothing can inject YAML or shell."""

from __future__ import annotations

import base64
import gzip
import ipaddress
import json
import os
import re
import subprocess
import textwrap
from dataclasses import dataclass

from motel.cabins.errors import Fail
from motel.cabins.tailnet import AUTHKEY_RE, TAG_RE
from motel.cabins.util import (
    ED25519_PUB_RE,
    LEASE_ID_RE,
    PACKAGE_RE,
    PRIVATE_KEY_RE,
    host_cidr,
    is_pos_int,
)

USER_DATA_LIMIT = 32 * 1024
EXPIRY_GRACE_S = 600
KEY_OPTIONS_RE = re.compile(r'^(?:,[a-z][a-z-]*(?:="[0-9.:]{1,64}")?){0,4}$')


@dataclass(frozen=True)
class GuestExtras:
    """Additions for a purpose-built guest (a tour guest). Built by ``motel.tours.guest.userdata_extras``.

    ``files``: cloud-init ``write_files`` list items, indented two spaces, to be added after the cabin's own files.
    ``boot``: bash lines, run by the cabin bootstrap after the cabin's own filter, access and disk steps.
    ``key_options``: extra authorized_keys options for the cabin key, each with a leading comma.
    All three are generated by trusted code from validated values; this module only checks their shape.
    """
    files: str
    boot: str
    key_options: str = ""


def ssh_keygen(directory, name, comment):
    """Generate an ed25519 keypair under a private directory; returns (private, public)."""
    path = os.path.join(directory, name)
    subprocess.run(["/usr/bin/ssh-keygen", "-q", "-t", "ed25519", "-N", "", "-C", comment, "-f", path],
                   stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                   check=True, env={"PATH": "/usr/bin:/bin"})
    with open(path, encoding="ascii") as handle:
        private = handle.read()
    with open(path + ".pub", encoding="ascii") as handle:
        public = " ".join(handle.read().split()[:2])
    return private, public


def guest_nft(mode: str, sources=()) -> str:
    """The guest packet filter. In ssh-allowlist mode only the host's exact addresses may reach TCP/22."""
    if mode == "tailscale":
        return textwrap.dedent("""\
            table inet cabin {
              chain input {
                type filter hook input priority 0; policy drop;
                iif "lo" accept
                ct state established,related accept
                iifname "tailscale0" tcp dport 22 accept
                udp sport 67 udp dport 68 accept
                icmp type { destination-unreachable, time-exceeded } accept
              }
              chain output {
                type filter hook output priority 0; policy accept;
                ip daddr 169.254.169.254 drop
                oifname "tailscale0" ct state established,related accept
                oifname "tailscale0" drop
              }
              chain forward {
                type filter hook forward priority 0; policy accept;
                iifname "tailscale0" drop
                oifname "tailscale0" drop
              }
            }
            """)
    if mode != "ssh-allowlist":
        raise Fail("unknown access mode")
    v4, v6 = [], []
    for src in sources:
        cidr = host_cidr(src)
        if cidr is None or cidr != src:
            raise Fail("guest firewall source must be one exact host address")
        net = ipaddress.ip_network(cidr)
        (v4 if net.version == 4 else v6).append(str(net.network_address))
    if not v4 and not v6:
        raise Fail("ssh-allowlist access needs at least one source address")
    lines = ["table inet cabin {", "  chain input {",
             "    type filter hook input priority 0; policy drop;",
             '    iif "lo" accept', "    ct state established,related accept"]
    if v4:
        lines.append("    ip saddr {{ {} }} tcp dport 22 accept".format(", ".join(sorted(v4))))
    if v6:
        lines.append("    ip6 saddr {{ {} }} tcp dport 22 accept".format(", ".join(sorted(v6))))
    lines += ["    udp sport 67 udp dport 68 accept",
              "    icmp type { destination-unreachable, time-exceeded } accept",
              "  }", "  chain output {", "    type filter hook output priority 0; policy accept;",
              "    ip daddr 169.254.169.254 drop", "  }",
              "  chain forward {", "    type filter hook forward priority 0; policy drop;", "  }", "}"]
    return "\n".join(lines) + "\n"


# A comment is "#" followed by a space or nothing at all: "#cloud-config", "#!/bin/bash", "#include" and "#includedir" lines are
# directives and stay.
_COMMENT_LINE = re.compile(r"^[ \t]*#(?: .*)?\n", re.M)


def _strip_comments(template: str) -> str:
    """The template without its comment-only lines: they explain the file to its maintainers and would only use up the
    provider's user-data limit. ``#cloud-config``, shebang and ``#include`` lines stay. Runs on the template alone, before any value is filled in."""
    first, _, rest = template.partition("\n")
    return first + "\n" + _COMMENT_LINE.sub("", rest)


def _indent(text: str, n: int) -> str:
    pad = " " * n
    return "\n".join((pad + line) if line.strip() else line for line in text.rstrip("\n").splitlines())


_TAILSCALE_FILES = """\
  - path: /run/motel-cabin/authkey
    permissions: '0600'
    encoding: b64
    content: {authkey}
  - path: /etc/systemd/system/tailscaled.service.d/10-cabin-firewall.conf
    permissions: '0644'
    content: |
      [Unit]
      Requires=cabin-guest-firewall.service
      After=cabin-guest-firewall.service
"""

_TAILSCALE_PREPACKAGES = """\
install -d -m 0755 /usr/share/keyrings
curl -fsSL --proto '=https' --tlsv1.2 https://pkgs.tailscale.com/stable/ubuntu/noble.noarmor.gpg \\
  -o /usr/share/keyrings/tailscale-archive-keyring.gpg
echo 'deb [signed-by=/usr/share/keyrings/tailscale-archive-keyring.gpg] https://pkgs.tailscale.com/stable/ubuntu noble main' \\
  > /etc/apt/sources.list.d/tailscale.list
"""

_TAILSCALE_ACCESS = """\
systemctl enable --now tailscaled
tailscale up --auth-key=file:/run/motel-cabin/authkey --hostname={name} --advertise-tags={tag} \\
  --accept-routes=false --accept-dns=false --ssh=false --advertise-exit-node=false
shred -u /run/motel-cabin/authkey
ts_ip=$(tailscale ip -4)
[[ $ts_ip =~ ^100\\.[0-9]+\\.[0-9]+\\.[0-9]+$ ]]
printf 'ListenAddress %s\\n' "$ts_ip" > /etc/ssh/sshd_config.d/05-cabin-listen.conf
systemctl daemon-reload
if systemctl is-enabled --quiet ssh.socket 2>/dev/null; then systemctl restart ssh.socket; else systemctl restart ssh; fi
"""

# ssh-allowlist: sshd stays on the public address; only the host's exact addresses are allowed in, by the
# provider firewall and again by the guest packet filter above.
_ALLOWLIST_ACCESS = """\
ts_ip=""
systemctl daemon-reload
if systemctl is-enabled --quiet ssh.socket 2>/dev/null; then systemctl restart ssh.socket; else systemctl restart ssh; fi
"""

_DISK = """\
dev=/dev/disk/by-id/scsi-0HC_Volume_{vid}
for _ in $(seq 1 60); do [ -b "$dev" ] && break; sleep 2; done
disk_state=failed
if [ -b "$dev" ]; then
  install -d -m 0755 /mnt/cabin-disk
  printf '%s /mnt/cabin-disk ext4 defaults,nofail,nodev,nosuid,discard 0 2\\n' "$dev" >> /etc/fstab
  systemctl daemon-reload
  if mount /mnt/cabin-disk; then
    chown cabin:cabin /mnt/cabin-disk
    cabin_home=$(getent passwd cabin | cut -d: -f6)
    ln -sfn /mnt/cabin-disk "$cabin_home/disk"
    disk_state=mounted
  fi
fi
"""


def render_user_data(template: str, *, rec, mode, host_private, host_public, client_public, controller_public,
                     guest_agent: bytes, packages, sources=(), tag=None, authkey=None, volume_id=None,
                     idle_seconds=1800, dns=("185.12.64.1", "185.12.64.2"), extras=None) -> str:
    """Fill the cloud-init template. Every value is validated, so nothing can inject YAML.

    ``extras`` (a :class:`GuestExtras`) adds the tour-guest profile. Without it the output is unchanged.
    """
    if not PRIVATE_KEY_RE.fullmatch(host_private):
        raise Fail("generated host key has an unexpected format")
    for pub in (host_public, client_public, controller_public):
        if not ED25519_PUB_RE.fullmatch(pub):
            raise Fail("invalid ed25519 public key")
    if not LEASE_ID_RE.fullmatch(rec["lease_id"]) or not all(PACKAGE_RE.fullmatch(p) for p in packages):
        raise Fail("invalid lease or package name")
    if volume_id is not None and not is_pos_int(volume_id):
        raise Fail("invalid volume id")
    try:
        resolvers = [str(ipaddress.IPv4Address(x)) for x in dns]
    except (ValueError, TypeError):
        raise Fail("invalid DNS resolver") from None
    if not resolvers:
        raise Fail("at least one DNS resolver is required")
    if mode == "tailscale":
        if not (authkey and AUTHKEY_RE.fullmatch(authkey) and tag and TAG_RE.fullmatch(tag)):
            raise Fail("invalid enrollment input")
        extra = _TAILSCALE_FILES.format(authkey=base64.b64encode(authkey.encode()).decode())
        pre = _TAILSCALE_PREPACKAGES
        access = _TAILSCALE_ACCESS.format(name=rec["name"], tag=tag)
        listen, before, extra_pkgs = "127.0.0.1", " tailscaled.service", ["nftables", "tailscale"]
    elif mode == "ssh-allowlist":
        extra, pre, access = "", "", _ALLOWLIST_ACCESS
        listen, before, extra_pkgs = "0.0.0.0", "", ["nftables"]
    else:
        raise Fail("unknown access mode")
    if extras is not None:
        if mode != "ssh-allowlist":
            raise Fail("a tour guest needs ssh-allowlist access (its packet filter would cut the tailnet)")
        if not (isinstance(extras, GuestExtras) and isinstance(extras.files, str) and isinstance(extras.boot, str)
                and isinstance(extras.key_options, str) and KEY_OPTIONS_RE.fullmatch(extras.key_options)):
            raise Fail("invalid guest extras")
        if "@@" in extras.files + extras.boot or "\x00" in extras.files + extras.boot:
            raise Fail("invalid guest extras")
    nft = guest_nft(mode, sources)
    lease_doc = json.dumps({"lease": rec["lease_id"], "name": rec["name"], "access": mode,
                            "expires": rec["expires_at"], "grace_s": EXPIRY_GRACE_S,
                            "idle_s": int(idle_seconds)}, sort_keys=True)
    values = {
        "HOST_PRIVATE": "".join("    " + line + "\n" for line in host_private.splitlines()).rstrip("\n"),
        "HOST_PUBLIC": host_public, "CLIENT_PUBLIC": client_public, "CONTROLLER_PUBLIC": controller_public,
        "GUEST_B64": base64.b64encode(gzip.compress(guest_agent, mtime=0)).decode(),
        "LEASE_B64": base64.b64encode(lease_doc.encode()).decode(),
        "DNS_RESOLVERS": " ".join(resolvers), "LISTEN_ADDR": listen, "FIREWALL_BEFORE": before,
        "NFT_RULES": _indent(nft, 6),
        "BOOT_PREPACKAGES": _indent(pre, 6) if pre else None,
        "BOOT_PACKAGES": " ".join(extra_pkgs + list(packages)),
        "BOOT_ACCESS": _indent(access, 6),
        "BOOT_DISK": _indent(_DISK.format(vid=volume_id), 6) if volume_id else _indent("disk_state=none", 6),
        "EXTRA_FILES": extra.rstrip("\n") if extra else None,
        "TOUR_FILES": extras.files.rstrip("\n") if extras is not None and extras.files else None,
        "BOOT_TOUR": _indent(extras.boot, 6) if extras is not None and extras.boot else None,
        "CABIN_KEY_OPTIONS": extras.key_options if extras is not None else "",
    }
    out = _strip_comments(template)
    for key, value in values.items():
        if value is None:           # drop the whole placeholder line
            out = out.replace("@@" + key + "@@\n", "")
        else:
            out = out.replace("@@" + key + "@@", value)
    if "@@" in out:
        raise Fail("cloud-init template has an unfilled placeholder")
    if len(out.encode()) > USER_DATA_LIMIT:
        raise Fail("user-data exceeds the provider limit")
    return out
